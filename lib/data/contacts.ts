import type { Contact, ContactChannel, ContactSector } from "./types";

const tel = (label: string, value: string): ContactChannel => ({
  kind: "phone",
  label,
  value,
  href: `tel:${value.split(" ")[0].split("–")[0].replace(/[^0-9]/g, "")}`,
});
const web = (label: string, url: string): ContactChannel => ({ kind: "web", label, value: url.replace(/^https?:\/\//, "").replace(/\/$/, ""), href: url });
