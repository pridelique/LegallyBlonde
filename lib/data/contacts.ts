const line = (label: string, id: string, href?: string): ContactChannel => ({ kind: "line", label, value: id, href });
const fb = (label: string, value: string, href?: string): ContactChannel => ({ kind: "facebook", label, value, href });
const note = (value: string): ContactChannel => ({ kind: "note", label: "", value });

